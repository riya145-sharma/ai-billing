<?php
declare(strict_types=1);

/**
 * Publish the web root into a hosting document root, keeping everything else private.
 *
 *   php bin/publish-public.php ../public_html
 *
 * Copies public/ (index.php, .htaccess, assets) into the target and writes
 * <target>/app-root.php, which tells index.php where the project is using a
 * path RELATIVE to the target — no absolute Hostinger or Windows paths.
 * Re-run after every deploy that changes public/.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require dirname(__DIR__) . '/bootstrap.php';

$targetArg = $argv[1] ?? '';
if ($targetArg === '') {
    fwrite(STDERR, "Usage: php bin/publish-public.php <document-root>\n  e.g. php bin/publish-public.php ../public_html\n");
    exit(1);
}

$norm = static fn(string $p): string => rtrim(str_replace('\\', '/', $p), '/');
$app = $norm((string)realpath(APP_ROOT));
$target = realpath($targetArg);
if ($target === false || !is_dir($target)) {
    fwrite(STDERR, "Target folder does not exist: {$targetArg}\n");
    exit(1);
}
$target = $norm($target);

if ($target === $app || str_starts_with($target . '/', $app . '/') || str_starts_with($app . '/', $target . '/')) {
    fwrite(STDERR, "The document root must be a separate folder next to the project, not the project itself or a folder inside/around it.\n"
        . "Expected layout:  domains/<domain>/ai-billing  (project)  +  domains/<domain>/public_html  (document root)\n");
    exit(1);
}

/** Relative path from directory $from to directory $to (both absolute, normalised). */
function relativePath(string $from, string $to): ?string
{
    $f = explode('/', trim($from, '/'));
    $t = explode('/', trim($to, '/'));
    // Different Windows drives: no relative path possible.
    if (preg_match('/^[A-Za-z]:$/', $f[0] ?? '') && strcasecmp($f[0], $t[0] ?? '') !== 0) {
        return null;
    }
    $i = 0;
    $windows = DIRECTORY_SEPARATOR === '\\';
    while ($i < count($f) && $i < count($t) && ($windows ? strcasecmp($f[$i], $t[$i]) === 0 : $f[$i] === $t[$i])) {
        $i++;
    }
    return implode('/', array_merge(array_fill(0, count($f) - $i, '..'), array_slice($t, $i)));
}

$rel = relativePath($target, $app);
if ($rel === null) {
    fwrite(STDERR, "Project and document root are on different drives; keep them on the same drive.\n");
    exit(1);
}

// Copy public/ → target
$src = $app . '/public';
$copied = 0;
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($src, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::SELF_FIRST);
foreach ($it as $f) {
    $sub = substr($norm($f->getPathname()), strlen($src) + 1);
    if ($sub === 'app-root.php') {
        continue;
    }
    $dest = $target . '/' . $sub;
    if ($f->isDir()) {
        is_dir($dest) || mkdir($dest, 0755, true);
    } elseif (!is_file($dest) || hash_file('sha256', $dest) !== hash_file('sha256', $f->getPathname())) {
        copy($f->getPathname(), $dest) || throw new RuntimeException("Copy failed: {$sub}");
        DIRECTORY_SEPARATOR === '/' && @chmod($dest, 0644);
        $copied++;
    }
}

$appRoot = "<?php\n// Generated by bin/publish-public.php — location of the private project folder,\n// relative to this document root. Re-run the script if you move either folder.\nreturn __DIR__ . '/" . addslashes($rel) . "';\n";
file_put_contents($target . '/app-root.php', $appRoot);
DIRECTORY_SEPARATOR === '/' && @chmod($target . '/app-root.php', 0644);

echo "Published public/ to {$targetArg} ({$copied} file(s) updated).\n";
echo "app-root.php → __DIR__ . '/{$rel}'\n";
foreach (['default.php', 'index.html', 'index.htm'] as $stray) {
    if (is_file($target . '/' . $stray)) {
        echo "Note: {$targetArg}/{$stray} exists (hosting placeholder). index.php takes priority, but you can delete it.\n";
    }
}
